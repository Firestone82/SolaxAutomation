    let current = 'en';

    /** Replaces {name} placeholders. */
    function interpolate(text, params) {
        if (!params) {
            return text;
        }

        return text.replace(/\{(\w+)}/g, (match, key) => (key in params ? params[key] : match));
    }

    return {
        get language() {
            return current;
        },

        setLanguage(language) {
            current = dictionaries[language] ? language : 'en';
            document.documentElement.lang = current;
        },

        /** Translated string, falling back to English and then to the key itself. */
        t(key, params) {
            const value = dictionaries[current]?.[key] ?? dictionaries.en[key] ?? key;
            return interpolate(value, params);
        },

        /** True when the active language (or English) actually defines this key. */
        has(key) {
            return Boolean(dictionaries[current]?.[key] ?? dictionaries.en[key]);
        },

        /**
         * Renders a backend message: prefers the translation for {@code key}, and falls back
         * to the English sentence the backend already rendered.
         */
        message(key, params, fallback) {
            return key && this.has(key) ? this.t(key, params) : (fallback ?? null);
        },

        /** Applies translations to every [data-i18n] and [data-i18n-title] element. */
        apply(root = document) {
            root.querySelectorAll('[data-i18n]').forEach(element => {
                element.textContent = this.t(element.dataset.i18n);
            });

            root.querySelectorAll('[data-i18n-title]').forEach(element => {
                element.title = this.t(element.dataset.i18nTitle);
            });
        }
    };
